#!/usr/bin/env python3
"""Generate portable CL curry wrappers and the alternative user package.

The checked-in catalog records standard interface arities, initially obtained
from SBCL 2.6.8's SB-INTROSPECT:FUNCTION-LAMBDA-LIST. Runtime code never uses
implementation introspection. Regenerate sources after reviewing catalog edits.
"""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path(__file__).with_name('cl-functions.json')

def symbol(name):
    return '#:' + name.lower()

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    def write(path, content):
        if args.check:
            if not path.is_file() or path.read_text()!=content:
                raise SystemExit(f'Generated source is stale: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
    rows = json.loads(CATALOG.read_text())['functions']
    names = [row['name'] for row in rows]
    assert len(names) == len(set(names))
    exports = '\n'.join('    ' + ' '.join(symbol(n + '/C') for n in names[i:i+6]) for i in range(0,len(names),6))
    catalog = ''';;; Generated by tools/curry/generate-cl.py; edit the reviewed JSON catalog.
(uiop:define-package #:ooparts/curry/catalog
  (:use #:cl)
  (:export #:*cl-functions*))
(in-package #:ooparts/curry/catalog)
(defparameter *cl-functions*
  '(\n'''
    catalog += ''.join(f'    ("{r["name"]}" {r["required"]})\n' for r in rows) + '    ))\n'
    write(ROOT/'src/curry/catalog.lisp', catalog)
    cl = ''';;; Generated exports; wrapper bodies are generated by the macro below.
(uiop:define-package #:ooparts/curry/cl
  (:use #:cl)
  (:import-from #:ooparts/curry/core #:%dispatch #:%record-wrapper #:%call-standard)
  (:import-from #:ooparts/curry/catalog #:*cl-functions*)
  (:export
''' + exports + '''))
(in-package #:ooparts/curry/cl)

(defmacro %define-standard-wrappers ()
  `(progn
     ,@(loop for (name required) in *cl-functions*
             for native = (or (find-symbol name :cl) (error "Unknown CL symbol ~A" name))
             for public = (intern (concatenate 'string name "/C") *package*)
             for arguments = (gensym "ARGUMENTS")
             for complete = (gensym "COMPLETE")
             for forms = (gensym "FORMS")
             for environment = (gensym "ENVIRONMENT")
             append
             `((defun ,public (&rest ,arguments)
                 (%dispatch (lambda (&rest ,complete) (%call-standard ',native ,complete))
                            ,required ,arguments))
               (define-setf-expander ,public (&rest ,forms &environment ,environment)
                 (get-setf-expansion (cons ',native ,forms) ,environment))
               (eval-when (:load-toplevel :execute)
                 (%record-wrapper ',public ',native ,required))))))

(%define-standard-wrappers)
'''
    write(ROOT/'src/curry/cl.lisp', cl)
    operators = ['DEFUN','FLET','LABELS','LAMBDA','DEFGENERIC','DEFMETHOD','DEFCLASS','DEFSTRUCT','DEFINE-CONDITION']
    shadow = sorted(names+operators+['FUNCTION'])
    # Export all standard symbols: unchanged ones are inherited CL symbols.
    user = ''';;; Generated namespace declarations; see tools/curry/generate-cl.py.
(uiop:define-package #:ooparts/curry/user
  (:use #:cl)
  (:import-from #:ooparts/curry #:curry #:uncurried-function)
  (:import-from #:ooparts/curry/catalog #:*cl-functions*)
  (:shadow\n'''
    user += '\n'.join('    '+' '.join(symbol(n) for n in shadow[i:i+7]) for i in range(0,len(shadow),7)) + ''')
  (:export #:enter #:*curried-readtable* #:curry #:uncurried-function))
(in-package #:ooparts/curry/user)

;; Qualify bootstrap code: this package deliberately replaces CL function names.
(cl:eval-when (:compile-toplevel :load-toplevel :execute)
  (cl:dolist (entry *cl-functions*)
    (cl:destructuring-bind (name required) entry
      (cl:let ((public (cl:intern name (cl:find-package :ooparts/curry/user)))
               (wrapper (cl:find-symbol (cl:concatenate 'cl:string name "/C") :ooparts/curry)))
        (cl:setf (cl:fdefinition public) (cl:fdefinition wrapper))
        (ooparts/curry/core::%record-wrapper public (cl:find-symbol name :cl) required)
        (cl:eval `(cl:declaim (cl:ftype (cl:function (cl:&rest cl:t) cl:*) ,public)))
        (cl:eval `(cl:define-setf-expander ,public (cl:&rest forms cl:&environment environment)
                    (cl:get-setf-expansion (cl:cons ',(cl:find-symbol name :cl) forms) environment))))))
  (cl:dolist (name '("DEFUN" "FLET" "LABELS" "LAMBDA" "DEFGENERIC" "DEFMETHOD"
                    "DEFCLASS" "DEFSTRUCT" "DEFINE-CONDITION"))
    (cl:let ((public (cl:intern name (cl:find-package :ooparts/curry/user)))
             (wrapper (cl:find-symbol (cl:concatenate 'cl:string name "/C") :ooparts/curry)))
      (cl:setf (cl:macro-function public)
               (cl:lambda (form environment)
                 (cl:macroexpand-1 (cl:cons wrapper (cl:cdr form)) environment)))))
  ;; Preserve standard type and class meanings for names that are also functions.
  (cl:dolist (name '("ATOM" "BIT" "CHARACTER" "COMPLEX" "CONS" "EQL" "FLOAT"
                    "FUNCTION" "LIST" "MEMBER" "MOD" "NOT" "NULL" "STRING" "VALUES" "VECTOR"))
    (cl:let ((public (cl:intern name (cl:find-package :ooparts/curry/user)))
             (native (cl:find-symbol name :cl)))
      (cl:eval `(cl:deftype ,public (cl:&rest parameters)
                  (cl:if parameters (cl:cons ',native parameters) ',native)))
      ))
  (cl:setf (cl:macro-function 'function)
           (cl:lambda (form environment)
             (cl:declare (cl:ignore environment))
             (cl:let ((argument (cl:second form)))
               (cl:if (cl:and (cl:consp argument) (cl:eq (cl:car argument) 'lambda))
                      (cl:cons 'ooparts/curry:lambda/c (cl:cdr argument))
                      (cl:list 'cl:function argument)))))
  (cl:do-external-symbols (native :cl)
    (cl:export (cl:list (cl:find-symbol (cl:symbol-name native) :ooparts/curry/user))
               :ooparts/curry/user)))

(cl:defvar *curried-readtable* (cl:copy-readtable cl:nil))
(cl:set-dispatch-macro-character
 #\\# #\\'
 (cl:lambda (stream sub-character numeric-argument)
   (cl:declare (cl:ignore sub-character))
   (cl:when numeric-argument (cl:error "A numeric prefix is invalid for #'."))
   (cl:let ((form (cl:read stream cl:t cl:nil cl:t)))
     (cl:if (cl:and (cl:consp form) (cl:eq (cl:car form) 'lambda))
            (cl:cons 'ooparts/curry:lambda/c (cl:cdr form))
            (cl:list 'cl:function form))))
 *curried-readtable*)

(cl:defun enter ()
  "Select the curried user package and its readtable in the current dynamic scope."
  (cl:setf cl:*package* (cl:find-package :ooparts/curry/user)
           cl:*readtable* *curried-readtable*)
  cl:*package*)
'''
    write(ROOT/'src/curry/user.lisp', user)
    print(f'Generated {len(rows)} standard function wrappers and the user namespace.')

if __name__ == '__main__':
    main()
